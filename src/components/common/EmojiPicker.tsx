interface Props {
  value: string;
  onChange: (value: string) => void;
  label?: string;
}

export function EmojiPicker({ value, onChange, label = "Icono" }: Props) {
  const [activeGroup, setActiveGroup] = useState(EMOJI_GROUPS[0]!.key);
  const [search, setSearch] = useState("");

  const filteredGroups = useMemo(() => {
    const term = search.trim().toLocaleLowerCase("es");
    if (!term) return [];
    return EMOJI_GROUPS.filter((group) =>
      group.label.toLocaleLowerCase("es").includes(term) ||
      group.emojis.some((emoji) => emoji.includes(search.trim())),
    );
  }, [search]);

  const active = EMOJI_GROUPS.find((group) => group.key === activeGroup) ?? EMOJI_GROUPS[0]!;

  return (
    <div className="space-y-2.5">
      <div className="flex items-center justify-between gap-2">
        <Label>{label}</Label>
        <span className="grid h-12 w-12 place-items-center rounded-xl border bg-muted/50 text-3xl" aria-label="Icono seleccionado">{value}</span>
      </div>
      <Input
        value={search}
        onChange={(event) => setSearch(event.target.value)}
        placeholder="Buscar una categoría o pegar un emoji…"
        aria-label="Buscar emojis"
      />
      <div className="grid grid-cols-9 gap-1 rounded-xl border border-border/60 bg-muted/25 p-1.5">
        {EMOJI_GROUPS.map((group) => (
          <button
            key={group.key}
            type="button"
            title={group.label}
            aria-label={group.label}
            aria-pressed={activeGroup === group.key}
            onClick={() => { setActiveGroup(group.key); setSearch(""); }}
            className={"grid aspect-square min-w-0 place-items-center rounded-lg text-xl transition " + (
              activeGroup === group.key ? "bg-background shadow-sm ring-1 ring-primary/30" : "text-muted-foreground hover:bg-background/70"
            )}
          >
            {group.tab}
          </button>
        ))}
      </div>
      <div className="max-h-56 overflow-y-auto overscroll-contain rounded-xl border border-border/60 p-2 sm:max-h-64">
        {(search.trim() ? filteredGroups : [active]).length === 0 ? (
          <p className="py-6 text-center text-xs text-muted-foreground">No hay coincidencias. Puedes pegar tu emoji abajo.</p>
        ) : (
          (search.trim() ? filteredGroups : [active]).map((group) => (
            <section key={group.key} className="space-y-2.5">
              <p className="text-xs font-semibold text-muted-foreground">{group.label}</p>
              <div className="grid grid-cols-6 gap-1.5 sm:grid-cols-8">
                {group.emojis.map((emoji, index) => (
                  <button
                    key={group.key + "-" + index}
                    type="button"
                    aria-label={"Elegir " + emoji}
                    aria-pressed={value === emoji}
                    onClick={() => onChange(emoji)}
                    className={"grid h-12 w-12 place-items-center rounded-xl border text-2xl transition-all hover:scale-105 sm:h-14 sm:w-14 sm:text-3xl " + (
                      value === emoji ? "border-primary bg-primary/10 ring-2 ring-primary/20" : "border-border/60 bg-muted/40 hover:bg-accent"
                    )}
                  >
                    {emoji}
                  </button>
                ))}
              </div>
            </section>
          ))
        )}
      </div>
      <div className="space-y-1">
        <Label htmlFor="custom-emoji-value">O pega tu propio emoji</Label>
        <Input
          id="custom-emoji-value"
          value={value}
          onChange={(event) => onChange(event.target.value)}
          placeholder="Ej. 🥾"
          maxLength={12}
          aria-label="Emoji personalizado"
        />
      </div>
      <p className="text-[11px] text-muted-foreground">Categorías en el orden de WhatsApp. Emojis más grandes y fáciles de seleccionar.</p>
    </div>
  );
}
